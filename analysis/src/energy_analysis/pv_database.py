"""Reproducible statistics and browser exports from PV Parquet snapshots.

No live requests are made. Missing values remain unknown; group sums describe
reported values, never an estimate of unreported capacity or market coverage.
"""

from __future__ import annotations

import hashlib
import json
from datetime import datetime
from pathlib import Path
from typing import Any

import pandas as pd
import pyarrow as pa
import pyarrow.parquet as pq


def field_profile(path: Path) -> pd.DataFrame:
    """Count known/missing values for every column, including all-null columns.

    Completeness is non-null coverage, not accuracy or applicability. Empty lists
    are reported values. False and zero are known values.
    """
    table = pq.read_table(path)
    records = []
    for field, column in zip(table.schema, table.columns, strict=True):
        metadata = field.metadata or {}
        records.append(
            {
                "field": field.name,
                "type": str(field.type),
                "unit": metadata.get(b"unit", b"").decode(),
                "known": len(column) - column.null_count,
                "missing": column.null_count,
                "coverage_pct": (
                    100 * (len(column) - column.null_count) / len(column) if len(column) else None
                ),
            }
        )
    return pd.DataFrame(records).set_index("field")


def grouped_statistics(path: Path, by: str, value: str) -> pd.DataFrame:
    """Group records and a numeric field, retaining unknown groups and values.

    reported_sum includes only known values (all-missing groups stay null).
    complete_sum is null unless *every* row in the group reports the field.
    Never add AC, DC, unspecified capacity or parent/phase records together.
    """
    schema = pq.read_schema(path)
    value_type = schema.field(value).type
    if not (pa.types.is_integer(value_type) or pa.types.is_floating(value_type)):
        raise ValueError(f"{value} must be a numeric field, not {value_type}")
    if by == value:
        raise ValueError("Grouping and numeric fields must differ")
    frame = pd.read_parquet(path, columns=[by, value])
    groups = frame.groupby(by, dropna=False, sort=True)[value]
    result = frame.groupby(by, dropna=False, sort=True).agg(
        records=(value, "size"),
        known=(value, "count"),
        mean=(value, "mean"),
        median=(value, "median"),
    )
    result["missing"] = result["records"] - result["known"]
    result["reported_sum"] = groups.sum(min_count=1)
    result["complete_sum"] = result["reported_sum"].where(result["missing"].eq(0))
    return result


def snapshot_overview(snapshot: Path) -> pd.DataFrame:
    """Read actual Parquet metadata for row/column counts and physical file sizes."""
    manifest = json.loads((snapshot / "manifest.json").read_text())
    records = []
    for entity in manifest["tables"]:
        path = snapshot / f"{entity}.parquet"
        metadata = pq.read_metadata(path)
        records.append(
            {
                "table": entity,
                "rows": metadata.num_rows,
                "columns": len(pq.read_schema(path)),
                "parquet_bytes": path.stat().st_size,
            }
        )
    return pd.DataFrame(records).set_index("table")


def _json_value(value: Any) -> Any:
    if isinstance(value, datetime):
        return value.isoformat()
    return value


def export_viewer_data(snapshot: Path) -> dict[str, Any]:
    """Export lossless browser projections of the five published Parquet files.

    JSON is a derived delivery format, not an independently maintained database.
    All rows and populated fields are retained; omitted all-null columns are
    declared in the full schema and restored as null in the viewer. Lists stay
    lists and UTC timestamps use ISO 8601. Hashes bind each projection to Parquet.
    The snapshot must be trusted, generated by build_parquet.
    """
    manifest = json.loads((snapshot / "manifest.json").read_text())
    schema = json.loads((snapshot / "schema.json").read_text())
    index: dict[str, Any] = {
        "schema_version": manifest["schema_version"],
        "input_sha256": manifest["input_sha256"],
        "fields": schema["fields"],
        "tables": {},
    }
    for entity in schema["entity_types"]:
        path = snapshot / f"{entity}.parquet"
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        if digest != manifest["tables"][entity]["sha256"]:
            raise ValueError(f"Parquet checksum mismatch: {entity}")
        table = pq.read_table(path)
        if table.num_rows != manifest["tables"][entity]["rows"]:
            raise ValueError(f"Parquet row count mismatch: {entity}")
        columns = [
            field.name
            for field, column in zip(table.schema, table.columns, strict=True)
            if column.null_count < table.num_rows
        ]
        rows = [
            [_json_value(row[name]) for name in columns]
            for row in table.select(columns).to_pylist()
        ]
        payload = {
            "parquet_sha256": digest,
            "columns": columns,
            "rows": rows,
        }
        data = json.dumps(payload, ensure_ascii=False, separators=(",", ":"), allow_nan=False)
        filename = f"{entity}.viewer.json"
        (snapshot / filename).write_text(data + "\n", encoding="utf-8")
        index["tables"][entity] = {
            "rows": table.num_rows,
            "parquet": path.name,
            "parquet_sha256": digest,
            "viewer": filename,
            "viewer_sha256": hashlib.sha256((data + "\n").encode()).hexdigest(),
            "viewer_bytes": len((data + "\n").encode()),
        }
    (snapshot / "viewer-index.json").write_text(
        json.dumps(index, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    return index
